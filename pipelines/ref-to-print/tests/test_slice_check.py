"""Tests for slicer.slice_check using a fake slicer script (no real slicer needed)."""

from __future__ import annotations

import json
import stat
import sys
from pathlib import Path

import pytest

from checks.report import validate
from slicer.slice_check import main, parse_duration

GCODE = """; generated by fake
G1 X1 Y1
; estimated printing time (normal mode) = 1d 2h 3m 4s
; filament used [g] = 57.21
; total filament used [g] = 15.64
"""


def make_fake(tmp_path: Path, body: str) -> Path:
    gcode = tmp_path / "canned.gcode"
    gcode.write_text(GCODE)
    script = tmp_path / "fake_slicer.py"
    script.write_text(f"#!{sys.executable}\nimport sys, shutil\n"
                      f"inp, out = sys.argv[1], sys.argv[2]\n"
                      f"CANNED = {str(gcode)!r}\n{body}\n")
    script.chmod(script.stat().st_mode | stat.S_IEXEC)
    return script


@pytest.fixture
def env(tmp_path, monkeypatch):
    monkeypatch.delenv("R2P_SLICER", raising=False)
    monkeypatch.setenv("R2P_SLICER_CMD", "{slicer} {input} {output}")
    return tmp_path


def run(tmp_path: Path, fake: Path, mesh: Path) -> tuple[int, dict]:
    rep = tmp_path / "rep.json"
    code = main(["--slicer", str(fake), "--mesh", str(mesh), "--out-dir", str(tmp_path / "out"),
                 "--report", str(rep)])
    return code, json.loads(rep.read_text())


def test_parse_duration():
    assert parse_duration("1d 2h 3m 4s") == 93784
    assert parse_duration("7h 55m 3s") == 28503
    assert parse_duration("45s") == 45
    assert parse_duration("none") is None


def test_success(env, cube, save_mesh):
    mesh = save_mesh(cube, env, "cube.stl")
    fake = make_fake(env, "shutil.copy(CANNED, out)")
    code, rep = run(env, fake, mesh)
    assert code == 0
    validate(rep, "slice.report")
    plate = rep["plates"][0]
    assert rep["passed"] and plate["passed"]
    assert plate["time_s"] == 93784
    assert plate["filament_g"] == 15.64
    assert (env / "out" / "cube.gcode").is_file()


def test_slicer_fails(env, cube, save_mesh):
    mesh = save_mesh(cube, env, "cube.stl")
    fake = make_fake(env, "sys.stderr.write('mesh is broken\\n'); sys.exit(1)")
    code, rep = run(env, fake, mesh)
    assert code == 1
    validate(rep, "slice.report")
    assert not rep["plates"][0]["passed"]
    assert any("mesh is broken" in e for e in rep["plates"][0]["errors"])


def test_no_output_file(env, cube, save_mesh):
    mesh = save_mesh(cube, env, "cube.stl")
    fake = make_fake(env, "pass")
    code, rep = run(env, fake, mesh)
    assert code == 1
    assert not rep["plates"][0]["passed"]
    assert rep["plates"][0]["errors"]


def test_no_slicer(tmp_path, monkeypatch, cube, save_mesh, capsys):
    monkeypatch.setenv("PATH", "")
    monkeypatch.delenv("R2P_SLICER", raising=False)
    monkeypatch.delenv("R2P_SLICER_CMD", raising=False)
    mesh = save_mesh(cube, tmp_path, "cube.stl")
    rep = tmp_path / "rep.json"
    assert main(["--mesh", str(mesh), "--report", str(rep)]) == 2
    assert not rep.exists()
    assert "no slicer" in capsys.readouterr().err


def test_job_dir(env, cube, save_mesh):
    save_mesh(cube, env, "parts/a.stl")
    save_mesh(cube, env, "parts/b.stl")
    manifest = {"schema": "parts.manifest/1", "job": "demo", "units": "mm", "up_axis": "Z",
                "clearance_mm": 0.3, "mates": [],
                "parts": [{"name": "a", "stl": "parts/a.stl"}, {"name": "b", "stl": "parts/b.stl"}]}
    (env / "parts.manifest.json").write_text(json.dumps(manifest))
    fake = make_fake(env, "shutil.copy(CANNED, out)")
    assert main(["--slicer", str(fake), "--job-dir", str(env)]) == 0
    rep = json.loads((env / "slice.report.json").read_text())
    validate(rep, "slice.report")
    assert rep["job"] == "demo" and len(rep["plates"]) == 2
    assert (env / "sliced" / "a.gcode").is_file() and (env / "sliced" / "b.gcode").is_file()
